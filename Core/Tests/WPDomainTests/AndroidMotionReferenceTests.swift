        let expected = [1.0, 0.875, 0.75, 0.625, 0.5, 0.625, 0.75, 0.875]
        for index in 0..<8 {
            XCTAssertEqual(SeasideEngine.emptySeatOpacity(time: Double(index) * 0.35 + 0.001, index: 0), expected[index])
            XCTAssertEqual(SeasideEngine.emptySeatOpacity(time: 0.001, index: index), expected[index])
        }
    }
    func testDropMatchesAndroidAtEverySixtiethSecond() {
        let engine = SeasideEngine(seed: 42); engine.skyAbove = 160
        engine.enter(.init(id: "drop", name: "guest", message: "hello", avatar: 7), drop: true, quiet: true)
        let rows = Self.android.split(separator: "\n")
        for (index, row) in rows.enumerated() {
            if index > 0 { engine.update(1.0 / 60) }
            let fields = row.split(separator: ",").map(String.init), actor = engine.actors[0]
            let actual = [engine.time, actor.x, actor.y, actor.top, actor.width, actor.height, actor.lift]
            for i in actual.indices { XCTAssertEqual(actual[i], Double(fields[i])!, accuracy: 0.0002, "frame \(index), field \(i)") }
            XCTAssertEqual(actor.pose, Int(fields[7]), "frame \(index)")
            XCTAssertEqual(actor.flying, fields[8] == "true", "frame \(index)")
            // Lifetimes vary with the platform RNG; emission and the expiry bounds are identical.
            if index <= 110 || index >= 122 { XCTAssertEqual(engine.particles.count, Int(fields[9]), "frame \(index)") }
            else { XCTAssertTrue((0...6).contains(engine.particles.count)) }
            XCTAssertEqual(actor.arrival != nil, fields[10] == "true", "frame \(index)")
        }
    }
