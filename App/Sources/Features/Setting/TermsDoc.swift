import Foundation

/// 웹 `app/setting/page.tsx` 의 TermsModal content 를 그대로 옮긴 약관 원문.
///
/// - Important: 법무 검토된 문구이므로 **웹·안드로이드와 내용이 달라지면 안 된다.**
///   수정이 필요하면 세 곳을 함께 고칠 것.
enum TermsDoc: String, CaseIterable, Identifiable {
    case privacy
    case location
    case thirdParty
    case marketing

    var id: String { rawValue }

    var title: String {
        switch self {
        case .privacy: return "개인정보 수집 및 이용 동의"
        case .location: return "위치정보 수집 및 이용 동의"
        case .thirdParty: return "개인정보 제3자 제공 동의"
        case .marketing: return "마케팅 목적 이용 동의"
        }
    }

    /// 동의 목록에 표시되는 라벨
    var label: String {
        switch self {
        case .privacy: return "(필수) 개인정보 수집 및 이용 동의"
        case .location: return "(필수) 위치정보 수집 및 이용 동의"
        case .thirdParty: return "(필수) 개인정보 제3자 제공 동의"
        case .marketing: return "(선택) 마케팅 목적 이용 동의"
        }
    }

    var body: String {
        switch self {
        case .privacy:
            return """
            본 서비스는 개인정보보호법 제15조에 따라 아래와 같이 개인정보를 수집 및 이용합니다.

            1. 수집 목적
            - 회원 가입 및 서비스 제공
            - 고객 상담 및 불만 처리
            - 서비스 이용 기록 분석 및 개선

            2. 수집 항목
            - (필수) 이름, 이메일 주소, 프로필 이미지
            - (필수) 소셜 로그인 식별자 (카카오톡, 구글, 네이버 등)

            3. 보유 및 이용 기간
            - 회원 탈퇴 시 지체 없이 파기
            - 단, 관계 법령에 따라 보존할 필요가 있는 경우 해당 법령에서 정한 기간 동안 보존합니다.

            4. 동의 거부 권리
            - 귀하는 개인정보 수집 및 이용에 대해 동의를 거부할 권리가 있습니다. 단, 필수 항목 동의 거부 시 서비스 이용이 제한될 수 있습니다.
            """

        case .location:
            return """
            본 서비스는 위치정보의 보호 및 이용 등에 관한 법률 제15조에 따라 아래와 같이 위치정보를 수집 및 이용합니다.

            1. 수집 목적
            - 예식장 위치 안내 및 하객 길찾기 서비스 제공
            - 위치 기반 웨딩 일정 관리 및 알림 기능 제공

            2. 수집 항목
            - (필수) GPS 좌표 (위도, 경도) 및 장소 정보

            3. 보유 및 이용 기간
            - 서비스 제공 목적 달성 시 또는 회원 탈퇴 시 지체 없이 파기합니다.

            4. 동의 거부 권리
            - 귀하는 위치정보 수집 및 이용에 대해 동의를 거부할 권리가 있습니다. 단, 동의 거부 시 위치 기반 기능(길안내 등) 이용이 제한됩니다.
            """

        case .thirdParty:
            return """
            본 서비스는 개인정보보호법 제17조에 따라 아래와 같이 개인정보를 제3자에게 제공합니다.

            1. 제공받는 자
            - 동일한 웨딩 플랜 룸(공유 룸)에 참여 및 초대된 다른 사용자

            2. 제공 목적
            - 일정, 예산, 채팅 등 웨딩 준비 데이터의 공동 관리 및 원활한 커뮤니케이션

            3. 제공 항목
            - (필수) 이름, 프로필 이미지, 채팅 내역, 일정 및 예산 입력 정보

            4. 보유 및 이용 기간
            - 웨딩 플랜 룸 참여 기간 동안 유지되며, 퇴장 시 또는 회원 탈퇴 시 파기됩니다.

            5. 동의 거부 권리
            - 귀하는 개인정보 제3자 제공에 대해 동의를 거부할 권리가 있습니다. 단, 동의 거부 시 플랜 공유 룸 기능 및 협업 서비스 이용이 불가능합니다.
            """

        case .marketing:
            return """
            1. 수집 및 이용 목적
            - 신규 서비스 및 업데이트 안내
            - 이벤트, 프로모션 알림 및 혜택 제공
            - 맞춤형 웨딩 정보 및 광고 전송 (앱 푸시, 이메일, 알림톡 등)

            2. 수집 항목
            - (선택) 이름, 이메일 주소, 서비스 이용 기록

            3. 보유 및 이용 기간
            - 회원 탈퇴 시 또는 마케팅 목적 이용 동의 철회 시까지 보관 및 이용됩니다.

            4. 동의 거부 권리
            - 귀하는 마케팅 목적 이용에 대한 동의를 선택적으로 거부하실 수 있습니다. 동의를 거부하셔도 웨딩 플랜트의 기본 서비스는 정상적으로 이용하실 수 있습니다.
            """
        }
    }
}
